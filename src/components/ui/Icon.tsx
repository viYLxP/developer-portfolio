export type IconName = keyof typeof paths

/** Icons that point "forward" and must mirror in right-to-left layouts. */
const directionalIcons: ReadonlySet<IconName> = new Set(['arrowForward'])

interface IconProps extends SVGProps<SVGSVGElement> {
  name: IconName
  size?: number
}

/** Decorative inline icon. Give the parent control an accessible name. */
export function Icon({ name, size = 20, className, ...rest }: IconProps) {
  const classes = ['icon', directionalIcons.has(name) && 'icon--directional', className].filter(Boolean).join(' ')
  return (
    <svg
      className={classes}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.8}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...rest}
    >
      {paths[name]}
    </svg>
  )
}
